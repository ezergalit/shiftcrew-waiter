// ══ השלילה בעברית — מודול משותף לכל המנועים ══
import { norm } from "./examEngine.js";
import { wMatch } from "./examEngine.js";
// ── שלילה: «בלי גלוטן» / «אין אלכוהול» אינם זיכוי; הכחשת אמת היא טעות ─────
// ⚠️ «אינ» (שגיאת כתיב של «אין») חמק מהשלילה והכחשת אלרגן קיבלה זיכוי מלא
// (נתפס ע"י סוכן שגיאות-הכתיב). הבדיקה עוברת דרך wMatch, לא דרך Set בלבד.
export const NEG_LIST = ["בלי", "ללא", "אין", "לא", "אינו", "אינה", "בלא", "בלי-", "איןן",
  "בליי", "לאא", "חוץ", "מלבד", "למעט", "טרם", "שלא", "ולא", "ובלי", "וללא", "ואין", "שאין"].map(norm);   // חוץ/מלבד/למעט = הכללה-שלילית
// ⚠️ **שוללים בהתאמה מדויקת בלבד.** רישול עליהם פסל מרכיבים תמימים —
// «לאבנה» התאים ל«אינה» ופסל את «זעתר טרי» שאחריו (שער האמת של Helios).
// שגיאות כתיב נסגרות ברשימה מפורשת, לא ב-Levenshtein.
export const NEGATORS = { has: (w) => NEG_LIST.includes(w) };
export const NEG_FILLER = new Set(["שום", "שם", "כל", "בכלל", "ממש", "אף", "בזה", "בו", "בה", "בהם", "בתוכו",
  "בתוכה", "פה", "כאן", "בפנים", "את", "מ", "מה",
  // פעלי הגשה/הכנה בין השולל ליעד: «לא מוגש נא», «לא מגיע חם», «לא עובר בישול»
  "מוגש", "מוגשת", "מגיע", "מגיעה", "עובר", "עוברת", "יוצא", "יוצאת", "נעשה"].map(norm));
// מסמני חיוב — «יש גלוטן, אין סויה»: ה«יש» מגן על «גלוטן» מהשלילה שאחריו.
export const AFFIRM = new Set(["יש", "מכיל", "מכילה", "כולל", "כוללת", "יהיה", "מגיע", "מגיעה"].map(norm));
export const MOD_CONTEXT = new Set(["אפשר", "ניתנ", "ניתן", "לבקש", "אופציה", "אופציונלי", "גמ", "או", "להזמינ", "להזמין", "רוצה", "מעדיפ", "מעדיף", "יכול", "יכולה", "אפשרות", "לקבל"].map(norm));
export function negIndex(aw) {
  const neg = new Array(aw.length).fill(false);
  for (let i = 0; i < aw.length; i++) {
    if (!NEGATORS.has(aw[i])) continue;
    // «אפשר בלי כיסונים» / «ניתן ללא גלוטן» / «לבקש בלי בצל» — הצעת שינוי, לא הכחשה: המנה מכילה
    // את זה כברירת מחדל (הבוטים על מרק פו, 6.9: «אפשר בלי כיסונים» סימן את הכיסונים כסותרים)
    if (MOD_CONTEXT.has(aw[i - 1]) || (aw[i - 1] && /^ל/.test(aw[i - 1]) && MOD_CONTEXT.has(aw[i - 2]))) continue;
    // קדימה: «אין גלוטן» · «בלי שום גלוטן» · **«אין בזה גלוטן»** — מילת-יחס/סרק
    // אחרי השולל מעבירה את היעד למילה שאחריה (נתפס: הכחשת אלרגן קיבלה 100%).
    if (i + 1 < aw.length) neg[i + 1] = true;
    const n1 = aw[i + 1];
    if (i + 2 < aw.length && (NEG_FILLER.has(n1) || /^(ב|מ)/.test(n1) && n1.length <= 4)) neg[i + 2] = true;
    // ⚠️ **אחורה, מרחק 1** — בעברית מדוברת השולל בא אחרי הנושא: «גלוטן אין
    // בכלל» · «ביצים אין בקרם» · «גלוטין אינ בזה». בלי זה הכחשת אלרגן קיבלה
    // 100% (שלושה סוכנים). **התנאי**: לשולל אין יעד קדימה — אחריו מילת-סרק
    // או צירוף יחס (ב־/ל־) או סוף משפט. «שום, לא כשר» ⇒ ל«לא» יש יעד קדימה
    // («כשר»), ולכן «שום» שלפניו נשאר תמים (נתפס בשער האמת של חזה עוף).
    // ⚠️ «לא ל-X» = «לא בשביל X» — ל-X הוא היעד («לא להריון» אינו שלילת
    // «חריף» שלפניו; נתפס בסט הסוכנים). רק ב-/מילת-סרק/סוף = אין יעד.
    const nxt = aw[i + 1], nxt2 = aw[i + 2];
    const fwdViaFiller = nxt && (NEG_FILLER.has(nxt) || /^ב/.test(nxt)) && nxt2 && !NEG_FILLER.has(nxt2) && !NEGATORS.has(nxt2);
    const noForwardTarget = (!nxt || NEG_FILLER.has(nxt) || /^ב/.test(nxt)) && !fwdViaFiller;
    if (i - 1 >= 0 && noForwardTarget && !(i - 2 >= 0 && AFFIRM.has(aw[i - 2])))
      neg[i - 1] = true;
  }
  return neg;
}
