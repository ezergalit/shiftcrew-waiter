// עכשיו לכל מסך יש שורה משלו, והיא מופיעה ברגע שמגיעים אליו — בכל סדר, ולאורך זמן.
// ⚠️ המסך נגזר מ**מצב האפליקציה** (`screenOf`) ולא מה-DOM, בדיוק כמו הפס עצמו:
