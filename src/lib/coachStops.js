  about: ({ hasGuide }) => (hasGuide
    ? "מי אנחנו וכללי הבית — מה שהמנהל רוצה שתדעו לפני המשמרת."
    : "קצת עלינו — מה שהמנהל רוצה שתדעו לפני המשמרת."),
  // 🔴 שתי השורות היו הפוכות: המסך הזה הוא רשימת התפריטים, לא הקטגוריות.
  // הנוסח מיותם (14.9), מילה במילה.
  "learn-door": "פה מתרגלים בעזרת כרטיסיות. אחרי מספיק תרגול נפתח הבוחן על אותו חלק בתפריט.",
  "learn-group": ({ menu }) => (menu
    ? `${menu}. נכנסים לקטגוריה ומתרגלים לקראת הבוחן.`
    : "נכנסים לקטגוריה ומתרגלים לקראת הבוחן."),
  // 🔴 כאן כבר **בתוך** הקטגוריה — כותרת «לתרגול X:», כפתור תרגול ורשימת המנות.
