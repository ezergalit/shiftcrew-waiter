export const GENERIC_PARTS = new Set(GENERIC_PARTS_RAW.map(nrm));
export const MODIFIERS = new Set([
  ...MOD_ROOTS_LONG.flatMap((r) => MOD_SUFFIX.map((s) => nrm(r + s))),
  ...MOD_SHORT.map(nrm),
]);
// בסיס/תיבול יסודי — ניטרלי בכל שאלה (ר' BASE_FREE ב-examEngine); כאן רק כדי שלא יהיו מפתחות
// («פלפל»/«ירק» אינם כאן בכוונה: ב«פלפלים קלויים», «פלפל חריף» הפלפל הוא המרכיב — הצ'יפ החשוף
// «פלפל» נשאר ניטרלי דרך BASE_FREE של המנוע, אלא אם הוא מפתח של יעד)
const BASE = new Set(["לחמ", "לחמנייה", "לחמניה", "לחמימ", "בצק", "מאפה", "פיתה", "פיתות", "אורז", "אצה", "אצות", "נורי", "קמח", "שמנ", "מלח", "מימ", "סוכר",
  "תבליני", "תבלינימ", "תבלינ", "רוטב"].map(nrm));

export const isModifier = (w) => MODIFIERS.has(nrm(w));
export const isGenericPart = (w) => GENERIC_PARTS.has(nrm(w));
export const isBaseWord = (w) => BASE.has(nrm(w));
/** מילה שלבדה אינה ידע על המנה — תואר, חלק כללי או בסיס */
export const isNonKey = (w) => isModifier(w) || isGenericPart(w) || isBaseWord(w);

/** מילות המפתח של ניסוח מרכיב — כל אחת לבדה עונה עליו. ריק ⇒ רק הניסוח המלא (או alt) עונה. */
export function ingredientKeys(phrase) {
  const ws = words(phrase);
  if (!ws.length) return [];
  if (ws.length === 1) return isBaseWord(ws[0]) || isModifier(ws[0]) ? [] : [ws[0]];
  const content = ws.filter((w) => !isNonKey(w) && (w.length >= 3 || SHORT_KEYS.has(w)));
  if (content.length) return content;
  // ניסוח שכולו חלקים/תארים («קרם גבינה יווני», «סלט ירוק», «פיתה יוונית») — החלק/הבסיס הוא
  // החומר: «גבינה»/«קרם»/«סלט»/«פיתה» עונים, התואר («יווני», «ירוק», «פריך») לעולם לא
  const parts = ws.filter((w) => isGenericPart(w) && !isModifier(w));
  return parts.length ? parts : ws.filter((w) => !isModifier(w) && w.length >= 3);
}

/** האם מילה (מנורמלת) היא מפתח של הניסוח */
export const isKeyOf = (w, phrase) => ingredientKeys(phrase).includes(nrm(w));
