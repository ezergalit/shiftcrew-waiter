// «אני כותב טונה וזה לא מוצא כי כתוב טונה אדומה.» מלצר קורא למרכיב בשם העצם שלו —
// «טונה», «בצל», «עגבניות» — ולא בתואר שהמנהל הצמיד לו בכרטיס (אדומה · ירוק · מיובשות ·
// קלויים · בולגרית). לכן לכל ניסוח מרכיב יש **מפתחות**: מילות התוכן שלו, בלי חלקים כלליים
// («פילה», «קרם», «רוטב», «גבינת») ובלי תארים (צבע · הכנה · מקור · גודל · טריות).
//   «טונה אדומה» ⇒ [טונה] · «פילה דניס» ⇒ [דניס] · «קרם אבוקדו כמהין» ⇒ [אבוקדו, כמהין]
//   «שמן זית» ⇒ [זית] · «עגבניות מיובשות» ⇒ [עגבניות] · «רוטב חריף» ⇒ [] (רק הניסוח המלא)
// מילת מפתח לבדה מזכה את המרכיב; תואר/חלק לבדו («אדום», «פילה», «קרם») אינו ידע ולא מזכה —
// וגם אינו טעות. ⚠️ שני מרכיבים באותה מנה שחולקים מפתח («טונה אדומה» ו«טרטר טונה») — «טונה»
// לבדה עונה על אחד מהם; לשני צריך מילה מבחינה.
// המודול עצמאי בכוונה (בלי import מ-examEngine) — examEngine מייבא אותו, ומעגל היה שובר את
// טעינת המודולים. אותו נרמול כמו norm: אותיות סופיות מקופלות, גרשיים ומקפים נזרקים.

export const nrm = (w) => String(w || "").toLowerCase()
  .replace(/['׳״"”“]/g, "").replace(/[־\-–—]/g, " ")
  .replace(/ך/g, "כ").replace(/ם/g, "מ").replace(/ן/g, "נ").replace(/ף/g, "פ").replace(/ץ/g, "צ")
  .replace(/[^a-z0-9א-ת ]/g, " ").replace(/\s+/g, " ").trim();
const STOP = new Set(["עמ", "של", "על", "או", "את", "ו", "ב", "ל", "מ", "כ", "ה"]);
export const words = (s) => nrm(s).split(" ").filter((w) => w.length > 1 && !STOP.has(w));

