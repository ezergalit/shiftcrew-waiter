// ══ מפתחות המרכיב + ההתאמה המדויקת (יותם, 6.9: «אני כותב טונה וזה לא מוצא כי כתוב טונה אדומה») ══
//   node tests/ingredientKeys.test.mjs
import { ingredientKeys, isNonKey } from "../src/lib/ingredientKeys.js";
import { grade, setMenuVocab, wMatch, wExact, norm } from "../src/lib/examEngine.js";
import { buildRows, markRows } from "../src/lib/describeLeaf.js";
let fail = 0;
const ok = (c, m) => { if (!c) { fail++; console.log("🔴", m); } };
const eq = (a, b) => JSON.stringify(a) === JSON.stringify(b);

// ── מפתחות ──
ok(eq(ingredientKeys("טונה אדומה"), ["טונה"]), "«טונה אדומה» ⇒ [טונה]");
ok(eq(ingredientKeys("פילה דניס"), ["דניס"]), "«פילה דניס» ⇒ [דניס]");
ok(eq(ingredientKeys("קרם אבוקדו כמהין"), ["אבוקדו", "כמהינ"]), "«קרם אבוקדו כמהין» ⇒ [אבוקדו, כמהין]");
ok(eq(ingredientKeys("שמן זית"), ["זית"]), "«שמן זית» ⇒ [זית]");
ok(eq(ingredientKeys("עגבניות מיובשות"), ["עגבניות"]), "«עגבניות מיובשות» ⇒ [עגבניות]");
ok(eq(ingredientKeys("פלפלים קלויים"), ["פלפלימ"]), "«פלפלים קלויים» ⇒ [פלפלים]");
ok(eq(ingredientKeys("קרם גבינה יווני"), ["קרמ", "גבינה"]), "כולו חלקים/תארים ⇒ החלקים הם החומר, התואר לא");
ok(eq(ingredientKeys("פיתה יוונית"), ["פיתה"]), "«פיתה יוונית» ⇒ [פיתה] (הבסיס כשאין מפתח אחר)");
ok(!ingredientKeys("מלח ים").includes("ימ") && !ingredientKeys("תרד בר").includes("בר"), "מילה בת 2 אותיות אינה מפתח («ים», «בר»)");
ok(eq(ingredientKeys("פילה בס"), ["בס"]) && eq(ingredientKeys("הל שחור"), ["הל"]), "בס/דג/הל — חריגים קצרים");
ok(isNonKey("אדומה") && isNonKey("קרמ") && isNonKey("פילה") && isNonKey("טרייה") && !isNonKey("טונה"), "isNonKey");

// ── המנוע העמום: קילוף בלי סובלנות, תחילית קצרה, זהות ──
ok(!wMatch("כמונ", "לימונ"), "«כמון» ≠ «לימון» (קילוף כ׳ + טעות-אות היה מזכה)");
ok(!wMatch("לימונ", "רימונימ"), "«לימון» ≠ «רימונים»");
ok(!wMatch("שומשומ", "שומ"), "«שומשום» ≠ «שום» (תחילית של 3 אותיות בהפרש 3)");
ok(wMatch("עגבנייה", "עגבניות") && wMatch("בצל", "בצלימ") && wMatch("ובצל", "בצל") && wMatch("מטוגנימ", "מטוגנ"), "רבים/תחילית/קילוף עדיין עובדים");
ok(wExact("זיתימ", "זיתי") && wExact("זית", "זיתי") && !wExact("קרמ", "קרמי") && !wExact("אטריות", "פטריות"), "wExact: סמיכות כן, תואר וטעות-אות לא");

// ── צ'יפים: מנה עם שני מרכיבים דומים — ההקצאה הנכונה ──
setMenuVocab([]);
const q = (targets) => ({ k: "recall", targets: targets.map((t) => ({ t, ctx: [] })), free: [], minOk: 1, maxInv: 1 });
const credited = (targets, chip) => grade(q(targets), [chip]).detail[0].credited;
ok(eq(credited(["טונה אדומה", "אבוקדו"], "טונה"), ["טונה אדומה"]), "«טונה» ⇒ טונה אדומה");
ok(eq(credited(["שום", "שמן שומשום"], "שומשום"), ["שמן שומשום"]), "«שומשום» ⇒ שמן שומשום, לא שום");
ok(eq(credited(["פטריות", "אטריות זכוכית"], "אטריות"), ["אטריות זכוכית"]), "«אטריות» ⇒ אטריות זכוכית, לא פטריות");
ok(eq(credited(["שמן זית", "זיתי קלמטה"], "זיתי"), ["זיתי קלמטה"]) && eq(credited(["זיתי קלמטה", "שמן זית"], "זית"), ["שמן זית"]), "«זיתי»/«זית» — כל אחד ליעד שלו");
ok(eq(credited(["קרם וניל", "קרמל אגוזים"], "קרמל"), ["קרמל אגוזים"]), "«קרמל» ⇒ קרמל אגוזים, לא קרם וניל");
ok(eq(credited(["ספייסי סלמון", "סלמון"], "סלמון"), ["סלמון"]), "«סלמון» לבדו ⇒ «סלמון», לא «ספייסי סלמון»");
ok(eq(credited(["לימון", "כמון"], "כמון"), ["כמון"]), "«כמון» ⇒ כמון");
for (const [targets, chip] of [[["טונה אדומה"], "אדומה"], [["קרם אבוקדו כמהין"], "קרם"], [["צ'ילי ירוק"], "ירוק"], [["פיתה יוונית"], "יוונית"], [["פלפל חריף"], "חריף"]]) {
  const d = grade(q(targets), [chip]).detail[0];
  ok(d.status === "free", `תואר/חלק לבדו «${chip}» — ניטרלי (${d.status})`);
}
ok(grade(q(["פלפלים קלויים"]), ["פלפל"]).detail[0].status === "ok", "«פלפל» (מילת בסיס) מזכה יעד שהוא מפתח שלו");

// ── תיאור חופשי: אותם כללים בשורות ──
const dish = (ings) => ({ name: "x", desc: "", ingredients: ings, pregnancy: [] });
const st = (ings, text) => Object.fromEntries(markRows(buildRows(dish(ings)), text).filter((r) => r.kind === "ing").map((r) => [r.canonical[0], r.status]));
ok(st(["טונה אדומה", "אבוקדו"], "יש בה טונה ואבוקדו")["טונה אדומה"] === "ok", "תיאור: «טונה» מסמן «טונה אדומה»");
ok(st(["פטריות", "אטריות זכוכית"], "עם אטריות")["פטריות"] === "miss", "תיאור: «אטריות» לא מסמן «פטריות»");
const s3 = st(["ספייסי סלמון", "סלמון"], "מגיע עם סלמון");
ok(s3["סלמון"] === "ok" && s3["ספייסי סלמון"] === "miss", "תיאור: «סלמון» אחד = השורה «סלמון», לא הספייסי");
const s4 = st(["בצל", "בצל ירוק"], "עם בצל ירוק");
ok(s4["בצל ירוק"] === "ok" && s4["בצל"] === "miss", "תיאור: «בצל ירוק» תופס את שתי המילים לפני «בצל»");
ok(st(["קרם אבוקדו כמהין"], "עם קרם")["קרם אבוקדו כמהין"] === "miss" && st(["טונה אדומה"], "משהו אדום")["טונה אדומה"] === "miss", "תיאור: חלק/תואר לבדו לא מסמן");
ok(st(["ירקות", "חסה אייסברג"], "עם חסה")["חסה אייסברג"] === "ok", "תיאור: «חסה» מסמן «חסה אייסברג» (המופע הכללי של ירקות לא גונב אותה)");

// ── אנגלית ⇒ עברית על צד התשובה (יותם, 1.9: תרגום אינו טעות) ──
ok(eq(credited(["טונה אדומה", "אבוקדו"], "tuna"), ["טונה אדומה"]) && eq(credited(["טונה אדומה", "אבוקדו"], "avocado"), ["אבוקדו"]), "tuna/avocado ⇒ טונה אדומה/אבוקדו");
ok(eq(credited(["עגבניות שרי", "בצל סגול"], "cherry tomato"), ["עגבניות שרי"]) && eq(credited(["עגבניות שרי", "בצל סגול"], "red onion"), ["בצל סגול"]), "צירופים באנגלית ⇒ הצירוף העברי");
ok(grade({ k: "recall", targets: [{ t: "גלוטן", alt: ["קמח", "חיטה"] }, { t: "לקטוז", alt: ["חלב"] }], free: [], minOk: 2, maxInv: 0 }, ["gluten", "dairy"]).lvl === 2, "gluten/dairy ⇒ גלוטן/לקטוז");
ok(grade(q(["צנונית"]), ["zzzqx"]).detail[0].status !== "wrong", "מילה זרה לא-מוכרת אינה «שגויה בביטחון» (שלד קצר לא מתאים לכל תפריט)");
console.log(fail ? `\n🔴 ${fail} כשלים` : "ingredientKeys.test: כל הבדיקות עברו");
process.exit(fail ? 1 : 0);
